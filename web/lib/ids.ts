/**
 * Проверка идентификатора проекта до обращения к базе.
 *
 * Идентификаторы у нас — UUID. Строка другой формы до базы доходить не
 * должна: Postgres отвечает на неё ошибкой приведения типа, и человек,
 * открывший ссылку с опечаткой, видел «ошибка запроса» вместо «не найдено».
 */
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export function isUuid(value: unknown): value is string {
  return typeof value === "string" && UUID.test(value);
}
